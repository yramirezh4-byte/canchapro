    private void btnCarbiarEstadoActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnCarbiarEstadoActionPerformed
        // TODO add your handling code here:
        
int fila = tablaCanchas.getSelectedRow();

if (fila == -1) {
    JOptionPane.showMessageDialog(this,
            "Seleccione una cancha de la tabla.");
    return;
}

String codigo = tablaCanchas.getValueAt(fila, 0).toString();

String[] opciones = {
    "DISPONIBLE",
    "MANTENIMIENTO",
    "INACTIVA"
};

String nuevoEstado = (String) JOptionPane.showInputDialog(
        this,
        "Seleccione el nuevo estado:",
        "Cambiar estado",
        JOptionPane.QUESTION_MESSAGE,
        null,
        opciones,
        opciones[0]
);

if (nuevoEstado == null) {
    return;
}

for (Cancha cancha : canchas) {
    if (cancha.getCodigo().equals(codigo)) {
        cancha.setEstado(nuevoEstado);
        break;
    }
}

archivo.guardarCanchas(canchas);
actualizarTabla();

JOptionPane.showMessageDialog(this,
        "Estado actualizado correctamente.");

    }//GEN-LAST:event_btnCarbiarEstadoActionPerformed



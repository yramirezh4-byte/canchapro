    private void btnConsultarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnConsultarActionPerformed
        // TODO add your handling code here:
        
try {

    if (cmbCancha.getSelectedItem() == null) {
        JOptionPane.showMessageDialog(this,
                "No hay canchas registradas.");
        return;
    }

    String seleccion = cmbCancha.getSelectedItem().toString();
    String codigo = seleccion.split(" - ")[0];

    LocalDate fecha = LocalDate.parse(
            txtFecha.getText().trim());

    LocalTime inicio = LocalTime.parse(
            txtHoraInicio.getText().trim());

    LocalTime fin = LocalTime.parse(
            txtHoraFin.getText().trim());

    ArchivoCancha archivo = new ArchivoCancha();
    ArrayList<Cancha> canchas = archivo.leerCanchas();

    Cancha seleccionada = null;

    for (Cancha cancha : canchas) {
        if (cancha.getCodigo().equals(codigo)) {
            seleccionada = cancha;
            break;
        }
    }

    if (seleccionada == null) {
        lblResultado.setText("Cancha no encontrada.");
        return;
    }

    if (!seleccionada.getEstado().equals("DISPONIBLE")) {
        lblResultado.setText("CANCHA NO DISPONIBLE");
        return;
    }

    if (!inicio.isBefore(fin)
            || inicio.isBefore(seleccionada.getHoraApertura())
            || fin.isAfter(seleccionada.getHoraCierre())) {

        lblResultado.setText("HORARIO NO VALIDO");
        return;
    }

    
boolean disponible = verificarReservas(
        seleccionada,
        fecha,
        inicio,
        fin
);

if (disponible) {

    lblResultado.setText(
            "CANCHA DISPONIBLE PARA RESERVAR");

} else {

    lblResultado.setText(
            "CANCHA OCUPADA EN ESE HORARIO");
}


} catch (DateTimeParseException e) {

    JOptionPane.showMessageDialog(this,
            "Revise la fecha (AAAA-MM-DD) y las horas (HH:mm).");
}

    }//GEN-LAST:event_btnConsultarActionPerformed



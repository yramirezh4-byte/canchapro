private boolean verificarReservas(
        Cancha cancha,
        LocalDate fecha,
        LocalTime inicio,
        LocalTime fin) {

    ArchivoCliente archivoCliente = new ArchivoCliente();
    ArchivoCancha archivoCancha = new ArchivoCancha();
    ArchivoReserva archivoReserva = new ArchivoReserva();

    ArrayList<Cliente> clientes =
            archivoCliente.leerClientes();

    ArrayList<Cancha> canchas =
            archivoCancha.leerCanchas();

    ArrayList<Reserva> reservas =
            archivoReserva.leerReservas(clientes, canchas);

    for (Reserva reserva : reservas) {

        if (reserva.getCancha().getCodigo()
                .equals(cancha.getCodigo())
                && reserva.getFecha().equals(fecha)
                && !reserva.getEstado().equalsIgnoreCase("CANCELADA")) {

            if (inicio.isBefore(reserva.getHoraFin())
                    && fin.isAfter(reserva.getHoraInicio())) {

                return false;
            }
        }
    }

    return true;
}
  
private void cargarCanchas() {

    cmbCancha.removeAllItems();

    ArchivoCancha archivo = new ArchivoCancha();
    ArrayList<Cancha> canchas = archivo.leerCanchas();

    for (Cancha cancha : canchas) {
        cmbCancha.addItem(
            cancha.getCodigo() + " - " + cancha.getNombre()
        );
    }
}

